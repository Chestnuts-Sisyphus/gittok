/** 六维合成：max(维) 打底，命中维度数（≥0.5）每多一维加 0.1，封顶 1.0。
 *  单点极强的卡不吃亏（max 保底），多点皆中的卡得加成（防止「哪一维都不突出」被平均掉）。 */
export function funFromDims(dims: Record<string, number | undefined>): number {
  const vals = FUN_DIMS.map((d) => {
    const v = dims[d.key];
    return typeof v === "number" && Number.isFinite(v) ? Math.max(0, Math.min(1, v)) : 0;
  });
  const max = Math.max(...vals, 0);
  const hits = vals.filter((v) => v >= 0.5).length;
  if (hits === 0) return 0;
  return Math.min(1, max + 0.1 * (hits - 1));
}

