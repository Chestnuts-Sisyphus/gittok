/**
 * 内容分区与乐趣判据的**唯一定义源**（v3，2026-09-14 晚）。
 *
 * 为什么要有这个文件：v2.2 的四区判定链是「3 个交互方式 + 1 个技术题材」混在
 * 一个枚举里（资源=学/看、创意=玩/创作、工具=干活 ← 交互方式；AI=靠智能干活 ← 题材），
 * 两个维度混排 → 数学上不可能互斥划分 → 工具区成兜底漏斗（实测占全库 48.7%，
 * 其中 33.3% 描述带 AI/模型/Agent 关键词）。栗子裁决：**四区不推翻，但边界必须
 * 「二分明确」**——工具区兜底可以，前提是工具区里任何一张卡都不可能属于其他三区。
 *
 * 解法：把四区判定改成**三分支二分链**（每步一个「是/否」，第一个答「是」的就是结果，
 * 三问全否 = 工具）。互斥性由构造保证：进入某区的条件是「前面所有分支都答否 + 本分支答是」，
 * 而工具区的条件是「三问全否」，因此工具区的卡在定义上不可能属于其余三区。
 *
 * 同时定义**乐趣六维**（fun_score 的判据体系）：v2.2 的 fun_score 只有一句
 * 「0=纯工具、1=极好玩（游戏/脑洞/创意玩具）」，实测退化成「游戏/AI-Agent 探测器」
 * （全库 234 张 ≥0.9 的卡里绝大多数是游戏或 AI Agent），且判定输入只有 160 字摘要
 * （detailCn 全文与 README 都没进模型）。v3 拆成六个可分别判定的成分，先拆再合。
 *
 * 纪律：本文件是**纯常量 + 纯函数**（前后端共用：web/src 直接 import）；
 * 判定链文本进 prompt，结构化判据进校验脚本，两者必须同源（禁止再复制一份）。
 */

